/**
 * Serialise a look formula into an Adobe/IRIDAS `.cube` 3D LUT, and read one back
 * the way the GPU does.
 *
 * The generator (`scripts/generate-looks.mjs`) writes these files; the verify
 * (`scripts/looks.verify.mjs`) regenerates them and compares, then samples the
 * committed file with `sampleCube` to prove the file it compared really is the
 * formula (a byte compare alone cannot see a wrong axis order or a wrong domain).
 *
 * Layout is the format every other tool expects and the one `src/gl/fx/cube.ts`
 * parses: red varies fastest, then green, then blue; `LUT_3D_SIZE` points span
 * DOMAIN_MIN..DOMAIN_MAX inclusive, so point i sits at i/(size-1).
 *
 * Pure: no Node imports, so the app project type-checks it and the scripts can
 * import it under tsx.
 */
import type { CubeLut } from '../fx/cube';
import type { LookFormula, Rgb } from './lookFormulas';

/** 25 samples per axis. Measured against 17/33 (see docs/d-job-implementation.md §76):
 * 25³ lands at 2.55/255 worst-case error against the formula and 33³ at 2.56/255 (the
 * residual is a clamp kink in one look, not resolution), while 17³ costs 5.62/255 — so
 * 25³ is the smallest grid that is visually exact, at 5.6 MB committed instead of 13 MB. */
export const CUBE_SIZE = 25;

const GENERATOR = 'scripts/generate-looks.mjs';

/** The value of one axis at grid index `i`. */
export function axisValue(i: number, size: number): number {
  return i / (size - 1);
}

/** One `.cube` file, byte for byte, with LF endings and fixed 6-decimal values. */
export function renderCubeText(look: LookFormula, size = CUBE_SIZE): string {
  const lines: string[] = [
    `# Generated by ${GENERATOR} from src/gl/looks/lookFormulas.ts — do not edit.`,
    `# Formula: ${look.id}`,
    `TITLE "vidlab ${look.id}"`,
    `LUT_3D_SIZE ${size}`,
    'DOMAIN_MIN 0 0 0',
    'DOMAIN_MAX 1 1 1',
  ];
  for (let b = 0; b < size; b += 1) {
    for (let g = 0; g < size; g += 1) {
      for (let r = 0; r < size; r += 1) {
        const out = look.grade([axisValue(r, size), axisValue(g, size), axisValue(b, size)]);
        lines.push(`${fmt(out[0])} ${fmt(out[1])} ${fmt(out[2])}`);
      }
    }
  }
  return `${lines.join('\n')}\n`;
}

function fmt(value: number): string {
  const clamped = value < 0 ? 0 : value > 1 ? 1 : value;
  return clamped.toFixed(6);
}

/**
 * Trilinear lookup with the same index mapping and clamping the runtime uses
 * (TEXTURE_3D, LINEAR, CLAMP_TO_EDGE) — so this is what the shader reads.
 */
export function sampleCube(lut: CubeLut, rgb: Rgb): Rgb {
  const n = lut.size;
  const axis = (v: number) => {
    const x = Math.min(1, Math.max(0, v)) * (n - 1);
    const i0 = Math.min(n - 1, Math.floor(x));
    const i1 = Math.min(n - 1, i0 + 1);
    return { i0, i1, f: x - i0 };
  };
  const at = (r: number, g: number, b: number): Rgb => {
    const base = ((b * n + g) * n + r) * 3;
    return [lut.data[base], lut.data[base + 1], lut.data[base + 2]];
  };
  const { i0: r0, i1: r1, f: fr } = axis(rgb[0]);
  const { i0: g0, i1: g1, f: fg } = axis(rgb[1]);
  const { i0: b0, i1: b1, f: fb } = axis(rgb[2]);
  const corners = [
    at(r0, g0, b0), at(r1, g0, b0), at(r0, g1, b0), at(r1, g1, b0),
    at(r0, g0, b1), at(r1, g0, b1), at(r0, g1, b1), at(r1, g1, b1),
  ];
  const mix = (a: number, b: number, t: number) => a + (b - a) * t;
  const out: number[] = [];
  for (let ch = 0; ch < 3; ch += 1) {
    const c00 = mix(corners[0][ch], corners[1][ch], fr);
    const c10 = mix(corners[2][ch], corners[3][ch], fr);
    const c01 = mix(corners[4][ch], corners[5][ch], fr);
    const c11 = mix(corners[6][ch], corners[7][ch], fr);
    out.push(mix(mix(c00, c10, fg), mix(c01, c11, fg), fb));
  }
  return [out[0], out[1], out[2]];
}
